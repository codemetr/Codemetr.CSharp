namespace Codemetr.CSharp.Tests;

public sealed class MeasurementIntegrityTests
{
    [Fact]
    public void PartialMetricsAggregateAndKeepDeclarationAndMemberProvenance()
    {
        var documents = new[] { new SourceDocument("b.cs", "partial class A { public void Second() { if (true) { } } }") ,
            new SourceDocument("a.cs", "partial class A { public void First() { } }") };
        var result = CodeAnalyzer.Analyze(documents);
        Assert.Equal(2, result.Types.Count);
        var whole = Assert.Single(result.WholeTypes);
        Assert.Equal(2, whole.PublicMethodCount);
        Assert.Equal(3, whole.TotalCyclomaticComplexity);
        Assert.Equal(["a.cs", "b.cs"], whole.Declarations.Select(site => site.File));
        Assert.Equal(["a.cs", "b.cs"], whole.Members.Select(member => member.File));
        var unsplit = Source.Type("class A { public void First() { } public void Second() { if (true) { } } }", "A");
        Assert.Equal(unsplit.TotalCyclomaticComplexity, whole.TotalCyclomaticComplexity);
        Assert.Equal(unsplit.ClassCoupling, whole.ClassCoupling);
        Assert.Equal(unsplit.PublicMethodCount, whole.PublicMethodCount);
        Assert.Equal(System.Text.Json.JsonSerializer.Serialize(whole), System.Text.Json.JsonSerializer.Serialize(CodeAnalyzer.Analyze(documents.Reverse().ToArray()).WholeTypes.Single()));
    }

    [Fact]
    public void ContextCounterpartIsMeasuredButHiddenPartsAreOnlyDisclosed()
    {
        var selected = new SourceDocument("a.cs", "partial class A { }");
        var other = new SourceDocument("b.cs", "partial class A { void M() { if (true) { } } }");
        var result = CodeAnalyzer.Analyze([selected], [selected, other]);
        Assert.Equal(1, result.DocumentCount);
        Assert.Equal("b.cs", Assert.Single(Assert.Single(result.WholeTypes).Members).File);
        var excluded = CodeAnalyzer.Analyze([selected], [selected, other], excluded: ["b.cs"]);
        Assert.Empty(Assert.Single(excluded.WholeTypes).Members);
        Assert.Equal("b.cs", Assert.Single(excluded.Completeness!.UnmeasuredPartialDeclarations).File);
        var generated = other with { Text = "// <auto-generated/>\n" + other.Text };
        Assert.Empty(Assert.Single(CodeAnalyzer.Analyze([selected], [generated]).WholeTypes).Members);
    }

    [Fact]
    public void PartialMethodImplementationCountsAsOnePublicMethod()
    {
        var result = CodeAnalyzer.Analyze([
            new SourceDocument("a.cs", "partial class A { public partial void M(); }"),
            new SourceDocument("b.cs", "partial class A { public partial void M() { } }")]);
        var type = Assert.Single(result.WholeTypes);
        Assert.Equal(1, type.PublicMethodCount);
        Assert.Single(type.Members);
    }

    [Fact]
    public void SemanticErrorsAndMissingReferencesAreAdvisoryAndExplicit()
    {
        var result = Source.Analyze("class A { Missing value; }");
        Assert.Empty(result.ParseErrors);
        Assert.True(result.Completeness!.SemanticErrorCount > 0);
        Assert.Contains("?Missing", result.Completeness.UnresolvedTypes);
        Assert.Empty(GuardEvaluator.Evaluate(result.Types, new CodemetrConfig()));
    }

    [Fact]
    public void WholeTypeGuardPreservesMemberFileOverrides()
    {
        var result = CodeAnalyzer.Analyze([
            new SourceDocument("a.cs", "partial class A { int M() { if (true) return 1; return 0; } }"),
            new SourceDocument("b.cs", "partial class A { int N() { if (true) return 1; return 0; } }")]);
        var config = new CodemetrConfig { Overrides = [new RuleOverride { Files = "b.cs", Rules = new GuardRules { MaxCyclomaticComplexity = 1 } }] };
        var finding = Assert.Single(GuardEvaluator.EvaluateWhole(result.WholeTypes, config));
        Assert.Equal("b.cs", finding.File);
        Assert.Equal("N()", finding.Member);
    }
    [Fact]
    public void SameLineSameNameTypesHaveSeparateIdentityAndCohesion()
    {
        var result = Source.Analyze("namespace X { partial class A { int x; void M() { x++; } void N() { x--; } } } namespace Y { partial class A { int y; void P() { y++; } void Q() { y--; } } }");
        Assert.Equal(["X.A", "Y.A"], result.WholeTypes.Select(type => type.FullName));
        Assert.All(result.WholeTypes, type => Assert.Equal(2, type.Members.Count));
        Assert.All(result.Cohesion, metric => { Assert.True(metric.Applicable); Assert.Single(metric.Groups); });
    }

    [Fact]
    public void InvalidAndInactiveCounterpartsRemainVisibleAsLimits()
    {
        var selected = new SourceDocument("a.cs", "partial class A { }");
        var broken = new SourceDocument("b.cs", "partial class A { void M( { }");
        var result = CodeAnalyzer.Analyze([selected], [broken]);
        Assert.Equal("b.cs", Assert.Single(result.Completeness!.UnmeasuredPartialDeclarations).File);
        var inactive = new SourceDocument("b.cs", "partial class A {\n#if HIDDEN\nvoid M() { }\n#endif\n}");
        var hidden = CodeAnalyzer.Analyze([selected], [inactive]);
        Assert.Contains("b.cs", hidden.Completeness!.InactiveFiles);
        Assert.Empty(Assert.Single(hidden.WholeTypes).Members);
    }

}
