namespace Codemetr.CSharp.Tests;

public sealed class SourceCollectorTests
{
    [Fact]
    public void SkipsBuildOutputGeneratedCodeAndExcludedGlobs()
    {
        using var dir = new TempDirectory();
        dir.Write("src/A.cs", "class A { }");
        dir.Write("src/bin/Debug/B.cs", "class B { }");
        dir.Write("src/obj/C.cs", "class C { }");
        dir.Write("src/D.g.cs", "class D { }");
        dir.Write("src/E.cs", "// <auto-generated/>\nclass E { }");
        dir.Write("src/F.cs", "class F { string S = \"// <auto-generated/>\"; }");
        dir.Write("src/Migrations/G.cs", "class G { }");
        dir.Write("README.md", "x");
        var documents = SourceCollector.Collect(dir.Path, ["."], ["**/Migrations/**"]);
        Assert.Equal(["src/A.cs", "src/F.cs"], documents.Select(d => d.Path));
    }

    [Fact]
    public void ExplicitMissingPathFailsButFileListsAreLenient()
    {
        using var dir = new TempDirectory();
        dir.Write("A.cs", "class A { }");
        Assert.Throws<FileNotFoundException>(() => SourceCollector.Collect(dir.Path, ["missing.cs"], []));
        Assert.Throws<FileNotFoundException>(() => SourceCollector.Collect(dir.Path, ["README.md"], []));
        var listed = SourceCollector.Collect(dir.Path, ["A.cs", "deleted.cs", "docs/x.md"], [], lenient: true);
        Assert.Equal(["A.cs"], listed.Select(d => d.Path));
    }
}
